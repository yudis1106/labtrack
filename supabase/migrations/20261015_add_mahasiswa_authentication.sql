-- LabTrack: autentikasi mahasiswa.
-- Admin tetap menggunakan kredensial environment variable yang sudah ada.

create table if not exists public.mahasiswa (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  nama text not null,
  nim text not null unique,
  email text not null unique,
  password_hash text not null,
  role text not null default 'mahasiswa',
  aktif boolean not null default true,
  constraint mahasiswa_role_check check (role = 'mahasiswa')
);

create index if not exists mahasiswa_nim_idx
  on public.mahasiswa (nim);

create index if not exists mahasiswa_email_idx
  on public.mahasiswa (lower(email));
